import { defineEndpoint, UsageModelKind } from "@shared/core";
import { z } from "zod";
import { zYoutubeTranscriptBody } from "./schema/inputs.ts";

/**
 * `POST /v1/youtube/transcript` — one video's transcript. Flat 1 unit per
 * call ⇒ leaf PER_CALL; a video with no transcript is a vendor non-2xx,
 * which the engine zero-bills.
 */
export default defineEndpoint({
    meta: {
        displayName: "Stophy YouTube Transcript",
        summary: "The transcript of a YouTube video.",
        description: "Get a YouTube video's transcript as `text`, with " +
            "`language`, `isAutoGenerated` and `durationSeconds`. Send " +
            "`videoUrl` or `videoId`, not both. Pick a caption language " +
            "with `language` (BCP 47, e.g. en or pt-BR), and set " +
            "`includeTimestamps` for timed `segments` " +
            "(`startSeconds`, `endSeconds`, `text`).",
        docsUrl:
            "https://docs.stophy.dev/api-reference/endpoint/youtube-transcript",
        categories: ["youtube"],
        notes: ["1 Stophy call per transcript returned."],
    },
    request: { method: "POST", path: "/youtube/transcript" },
    input: {
        schema: {
            body: z.union([
                zYoutubeTranscriptBody.omit({ videoId: true })
                    .required({ videoUrl: true }),
                zYoutubeTranscriptBody.omit({ videoUrl: true })
                    .required({ videoId: true }),
            ]),
        },
    },
    usage: {
        model: {
            kind: UsageModelKind.PER_CALL,
            label: "transcripts",
            consumes: { credit: "default", amount: 1 },
        },
    },
});
